// UI 움직임 곡선 (Phaser 없이 계산만 — 단위 테스트에서 바로 부른다)

/** 강화 버튼 느낌표 스케일 팝 곡선 (주기 0~1): 앞 30% 동안 1 → 1.35 → 0.92 → 1, 나머지는 쉼 (2026-11-19, 1.3초 주기·실제 시간) */
export function badgePop(p) {
  if (p >= 0.3) return 1;
  const t = p / 0.3;
  if (t < 0.35) return 1 + 0.35 * Math.sin((t / 0.35) * (Math.PI / 2));
  if (t < 0.7) return 1.35 - 0.43 * ((t - 0.35) / 0.35);
  return 0.92 + 0.08 * ((t - 0.7) / 0.3);
}
